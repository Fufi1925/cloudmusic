#!/usr/bin/env python3
"""Render every CloudMusic icon asset from branding/cloudmusic-logo.svg.

The master artwork is the uploaded cloud + notes mark (vectorised into
branding/cloudmusic-logo.svg). Everything below is derived from it, so a new
upload only needs to replace the master.

Outputs
  build/icon.svg, build/icon.png (1024), build/icon.ico, build/icons/<n>x<n>.png   electron-builder
  public/icon.png (512), public/favicon-16x16.png, public/apple-touch-icon.png    window icon + favicon
  src/assets/logo.svg                                                            in-app logo (mark, dark ink)
  src/assets/app-icon.svg                                                        full tile, used for the dock icon
  android/app/src/main/res/drawable/ic_launcher_foreground.xml                   adaptive icon
  android/app/src/main/res/drawable/ic_launcher_background.xml
  android/app/src/main/res/drawable/ic_launcher_monochrome.xml                   themed icon (Android 13+)
  android/app/src/main/res/drawable/ic_stat_cloudmusic.xml                       notification icon

Usage: python3 branding/generate-icons.py
Needs: rsvg-convert, ImageMagick `convert`.
"""
import os
import re
import shutil
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MASTER = os.path.join(HERE, "cloudmusic-logo.svg")
MARK = os.path.join(HERE, "cloudmusic-mark.svg")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable")

# the bitmap the mark was traced from, in potrace points (1 pt = 1/72 in here)
MARK_W, MARK_H = 843.0, 310.0
# potrace path data lives on a grid ten times finer than the mark box; the SVG
# wrappers scale it down with scale(0.1), the VectorDrawables do not
PATH_W, PATH_H = MARK_W * 10, MARK_H * 10

# adaptive icon geometry: 108dp canvas, 66dp safe zone
AD_CANVAS = 108.0
AD_ART_WIDTH = 64.0  # adaptive icons keep a 66dp safe circle
AD_SCALE = AD_ART_WIDTH / PATH_W


def run(*cmd):
    subprocess.run(cmd, check=True)


def render(svg, size, out, height=None):
    cmd = ["rsvg-convert", "-w", str(size)]
    if height is not None:
        cmd += ["-h", str(height)]
    run(*cmd, svg, "-o", out)


def mark_group(fill, indent=8):
    """The traced mark as an SVG group; potrace output is y-up, so it is flipped."""
    pad = " " * indent
    inner = open(MARK).read()
    body = re.search(r"(<g transform=\"translate\(0 310\.?0?\)[^>]*>.*?</g>)", inner, re.S)
    if not body:
        raise SystemExit("branding/cloudmusic-mark.svg has no traced group")
    group = body.group(1).replace('fill="#0B0B0C"', f'fill="{fill}"')
    return "\n".join(pad + line.strip() for line in group.splitlines())


def android_paths(fill, indent=8):
    """The same group as VectorDrawable <path> elements (potrace path data is valid there)."""
    pad = " " * indent
    inner = open(MARK).read()
    paths = re.findall(r"<path d=\"([^\"]+)\"", inner, re.S)
    if not paths:
        raise SystemExit("branding/cloudmusic-mark.svg has no paths")
    return "\n".join(f'{pad}<path android:fillColor="{fill}" android:pathData="{" ".join(p.split())}"/>' for p in paths)


def f(v):
    return f"{float(v):.3f}".rstrip("0").rstrip(".")


def desktop_assets():
    os.makedirs(os.path.join(ROOT, "build", "icons"), exist_ok=True)
    shutil.copyfile(MASTER, os.path.join(ROOT, "build", "icon.svg"))
    shutil.copyfile(MASTER, os.path.join(ROOT, "public", "app-icon.svg"))
    shutil.copyfile(MASTER, os.path.join(ROOT, "src", "assets", "app-icon.svg"))
    render(MASTER, 1024, os.path.join(ROOT, "build", "icon.png"))
    render(MASTER, 512, os.path.join(ROOT, "public", "icon.png"))
    render(MASTER, 180, os.path.join(ROOT, "public", "apple-touch-icon.png"))
    for n in (16, 32, 48, 64, 128, 256, 512):
        render(MASTER, n, os.path.join(ROOT, "build", "icons", f"{n}x{n}.png"))
    render(MASTER, 16, os.path.join(ROOT, "public", "favicon-16x16.png"))
    parts = []
    for n in (16, 24, 32, 48, 64, 128, 256):
        p = os.path.join(ROOT, "build", f"ico-{n}.png")
        render(MASTER, n, p)
        parts.append(p)
    run("convert", *parts, os.path.join(ROOT, "build", "icon.ico"))
    for p in parts:
        os.remove(p)


def local_variant():
    """Square variant without the tile: just the mark on a transparent square (taskbar/favicon fallbacks)."""
    s = 128 / MARK_W
    h = MARK_H * s
    y = (128 - h) / 2
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
  <title>CloudMusic</title>
  <g transform="translate(0 {f(y)}) scale({s:.6f})">
{mark_group("#0B0B0C", 4)}
  </g>
</svg>
'''


HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by branding/generate-icons.py from branding/cloudmusic-logo.svg -->\n'


def write(name, body):
    with open(os.path.join(RES, name), "w") as fh:
        fh.write(HEADER + body)


def android_assets():
    # background: the white tile fill, full bleed so any mask crops cleanly
    write("ic_launcher_background.xml", '''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFFFF" android:pathData="M0,0h108v108h-108z"/>
</vector>
''')

    # foreground: mark centred inside the 66dp safe zone.
    # VectorDrawable applies scale before translate, and potrace draws y-up, so the
    # group flips vertically and translates to the artwork's bottom edge.
    y = (AD_CANVAS - PATH_H * AD_SCALE) / 2
    ty = y + PATH_H * AD_SCALE
    x = (AD_CANVAS - AD_ART_WIDTH) / 2
    write("ic_launcher_foreground.xml", f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{f(x)}" android:translateY="{f(ty)}" android:scaleX="{AD_SCALE:.6f}" android:scaleY="-{AD_SCALE:.6f}">
{android_paths("#FF0B0B0C", 8)}
    </group>
</vector>
''')

    write("ic_launcher_monochrome.xml", f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{f(x)}" android:translateY="{f(ty)}" android:scaleX="{AD_SCALE:.6f}" android:scaleY="-{AD_SCALE:.6f}">
{android_paths("#FFFFFFFF", 8)}
    </group>
</vector>
''')

    # notification icon: 24dp, mark spans the width with a little breathing room
    scale = 20.0 / PATH_W
    y24 = (24 - PATH_H * scale) / 2
    ty24 = y24 + PATH_H * scale
    write("ic_stat_cloudmusic.xml", f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="24" android:viewportHeight="24">
    <group android:translateX="2" android:translateY="{f(ty24)}" android:scaleX="{scale:.6f}" android:scaleY="-{scale:.6f}">
{android_paths("#FFFFFFFF", 8)}
    </group>
</vector>
''')


if __name__ == "__main__":
    desktop_assets()
    with open(os.path.join(ROOT, "src", "assets", "logo.svg"), "w") as fh:
        fh.write(local_variant())
    android_assets()
    print("icons written")
